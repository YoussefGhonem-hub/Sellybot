        static readonly Dictionary<int, ShopGov> ById = All.ToDictionary(g => g.Id);
        public static ShopGov Get(int id) { ShopGov g; return ById.TryGetValue(id, out g) ? g : null; }
        public static string Name(int id, bool en = false) { var g = Get(id); return g == null ? "" : en ? g.En : g.Ar; }

        // "المنصورة" / "اسكندرية" / "cairo" -> the governorate (a city's name counts), for the assistant and Excel. null = not known.
        public static ShopGov Find(string text, out string city)
        {
            city = null;
            var t = Fold(text);
            if (t.Length < 2) return null;
            foreach (var g in All) if (Fold(g.Ar) == t || g.En.ToLowerInvariant() == t) return g;
            foreach (var g in All) foreach (var x in g.Cities) if (Fold(x) == t) { city = x; return g; }
            foreach (var g in All) { var f = Fold(g.Ar); if (f.Length > 3 && (t.Contains(f) || (t.Length > 3 && f.Contains(t)))) return g; }
            foreach (var g in All) foreach (var x in g.Cities) { var f = Fold(x); if (f.Length > 3 && (t.Contains(f) || (t.Length > 3 && f.Contains(t)))) { city = x; return g; } }
            return null;
        }
        public static string Fold(string s)
        {
            if (string.IsNullOrWhiteSpace(s)) return "";
            var t = s.Trim().ToLowerInvariant().Replace('أ', 'ا').Replace('إ', 'ا').Replace('آ', 'ا').Replace('ة', 'ه').Replace('ى', 'ي').Replace("محافظة ", "").Replace("محافظه ", "").Replace("مدينة ", "").Replace("مدينه ", "").Trim();
            var w = t.Split(' ').Select(x => x.StartsWith("ال") && x.Length > 4 ? x.Substring(2) : x);
            return string.Join(" ", w);
        }

